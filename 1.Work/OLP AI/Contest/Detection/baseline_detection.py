class DetectionDataset(Dataset):
    def __init__(self, samples, img_dir, transform, is_test=False):
        self.samples = samples
        self.img_dir = img_dir
        self.transform = transform
        self.is_test = is_test

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        if self.is_test:
            image_name = self.samples[idx]
        else:
            image_name, boxes, labels = self.samples[idx]

        image = Image.open(self.img_dir / image_name).convert("RGB")
        image = self.transform(image)

        if self.is_test:
            return image, image_name

        boxes = torch.tensor(boxes, dtype=torch.float32).reshape(-1, 4)
        labels = torch.tensor(labels, dtype=torch.int64).reshape(-1)

        target = {
            "boxes": boxes,
            "labels": labels,
            "image_id": torch.tensor(idx),
            "area": (
                (boxes[:, 2] - boxes[:, 0])
                * (boxes[:, 3] - boxes[:, 1])
            ),
            "iscrowd": torch.zeros(len(boxes), dtype=torch.int64),
        }

        return image, target


